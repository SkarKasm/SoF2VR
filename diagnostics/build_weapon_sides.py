"""Restore original complementary view-mesh sides; compare original dropped models.
No web artwork or replacement weapon design is involved. Original PK3s untouched.
"""
from pathlib import Path
import json,struct,zipfile
ROOT=Path(__file__).resolve().parents[1];BASE=ROOT.parent/'Soldier of Fortune 2/base'
def surfaces(d):
 h=struct.unpack_from('<4si64s64s7i',d);out=[]
 for i in range(h[8]):
  at=164+struct.unpack_from('<i',d,164+i*4)[0];name=d[at:at+64].split(b'\0')[0].decode()
  flags=struct.unpack_from('<i',d,at+64)[0];p=h[7]+4+struct.unpack_from('<i',d,h[7]+4+i*4)[0]
  row=struct.unpack_from('<10i',d,p);out.append(dict(name=name,flags=flags,triangles=row[5]))
 return out
rows=json.loads((ROOT/'resources/weapon_parts.json').read_text())['weapons'];report=[]
# The M203 is a separate Ghoul2 bolton, not a surface in the M4 view model.
# Its original back/underside pieces must follow its own moving-part state.
rows.append(dict(id=9,name='M4 M203 bolton',viewModel='models/weapons/m203/m203.glm',archive='models.pk3'))
header=['/* Generated by diagnostics/build_weapon_sides.py from local originals. */','#ifndef SOF2_WEAPON_SIDES_H','#define SOF2_WEAPON_SIDES_H','typedef struct {const char *path; int count; int surfaces[64]; int bases[64]; unsigned defaults[64];} VRWeaponSides;','static const VRWeaponSides vrWeaponSides[]={']
for row in rows:
 with zipfile.ZipFile(BASE/row['archive']) as z:
  surf=surfaces(z.read(row['viewModel']));names={s['name']:i for i,s in enumerate(surf)};pairs=[]
  for i,s in enumerate(surf):
   n=s['name'];root=None
   if n.endswith('h_off') and n[:-5]+'_off' in names:root=n[:-5]+'_off'
   elif not n.endswith('_off'):
    for suffix in ['fb','h','r','l','f','b']:
     if n.endswith(suffix):
      base=n[:-len(suffix)]
      if base in names:root=base;break
      if base+'a' in names:root=base+'a';break
   if root is not None:pairs.append((i,names[root],surf[names[root]]['flags']&2))
   elif n in ['righthandleh','lefthandleh','rearringh','rpg7backh','gunstock']:pairs.append((i,-1,0))
  prefix=row['viewModel'].rsplit('/',1)[0]+'/world/'
  worlds=[dict(path=n,surfaces=surfaces(z.read(n))) for n in z.namelist() if n.startswith(prefix) and n.endswith('.glm')]
 if pairs:header.append(' {"%s",%d,{%s},{%s},{%s}},'%(row['viewModel'],len(pairs),','.join(str(p[0]) for p in pairs),','.join(str(p[1]) for p in pairs),','.join(str(p[2]) for p in pairs)))
 report.append(dict(id=row['id'],weapon=row['name'],viewModel=row['viewModel'],restored=[dict(surface=surf[a]['name'],index=a,base=b,triangles=surf[a]['triangles']) for a,b,f in pairs],droppedModels=worlds,method='authored complementary meshes; preserve base-part visibility',additionalInventedGeometry=False))
header+=['};','#endif',''];(ROOT/'src/weapon_sides.h').write_text('\n'.join(header))
(ROOT/'build/weapon-side-audit.json').write_text(json.dumps(report,indent=2)+'\n')
print('Compared',len(report),'original view models with dropped assets; restored',sum(len(w['restored']) for w in report),'complementary surfaces.')
